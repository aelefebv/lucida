#!/usr/bin/env node
// PROTOTYPE — throwaway. Renders every sample into ../SAMPLES.md so the output
// can be read from the issue without running anything.

import { writeFileSync } from 'node:fs';
import { SCENARIOS } from './modules/scenarios.mjs';
import { diagnose } from './modules/diagnose.mjs';
import { createRenderer } from './modules/render.mjs';
import { summaryProjection } from './cli.mjs';

const L = [];
L.push('# Sample agent-facing output');
L.push('');
L.push('Generated by `prototype/build-samples.mjs`. Do not hand-edit.');
L.push('');
L.push('Every run below is synthesized from the measured distributions in');
L.push('[#888](https://github.com/aelefebv/lucida/issues/888) and');
L.push('[#899](https://github.com/aelefebv/lucida/issues/899); see `README.md` for what is measured,');
L.push('what is interpolated, and what is invented.');
L.push('');

const sizes = [];
for (const [id, s] of Object.entries(SCENARIOS)) {
  const doc = diagnose(s.build());
  const text = createRenderer().render(doc, 'summary');
  const stages = createRenderer().render(doc, 'stages');
  const json = JSON.stringify(summaryProjection(doc), null, 2);
  const fullJson = JSON.stringify(doc, null, 2);
  sizes.push({ id, text: text.length, json: json.length, stages: stages.length, fullJson: fullJson.length });

  L.push(`## ${id} — ${s.label}`);
  L.push('');
  L.push(`**Default output** (${text.length} bytes, ${text.split('\n').length} lines) — what \`lucida trace <dataset>\` prints:`);
  L.push('');
  L.push('```');
  L.push(text);
  L.push('```');
  L.push('');
  L.push(`**Per-stage rollup** (${stages.length} bytes) — \`lucida trace show ${doc.runId} --stages\`:`);
  L.push('');
  L.push('```');
  L.push(stages);
  L.push('```');
  L.push('');
  L.push(`<details><summary>Default output as JSON (${json.length} bytes) — <code>--json</code></summary>`);
  L.push('');
  L.push('```json');
  L.push(json);
  L.push('```');
  L.push('');
  L.push('</details>');
  L.push('');
}

L.push('## Sizes');
L.push('');
L.push('| run | default text | default JSON | rollup text | full JSON |');
L.push('| --- | --- | --- | --- | --- |');
for (const s of sizes) L.push(`| ${s.id} | ${s.text} B | ${s.json} B | ${s.stages} B | ${s.fullJson} B |`);
L.push('');
L.push('Raw lifecycle rows are never in any of these. They leave through');
L.push('`lucida trace export <runId> --format chrome`, which writes a file and prints its path.');
L.push('');

const dest = new URL('../SAMPLES.md', import.meta.url);
writeFileSync(dest, L.join('\n'));
console.log(`wrote ${dest.pathname}`);
